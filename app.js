  <div class="poem-text">உன் ஸ்கூட்டராக
நான் மாறிவிட்டால்,
நீ செல்லும் பாதையெல்லாம்
என்னுடைய பயணமாகுமே…

உன் கைகளின் தொடுதலில்
ஒரு நிமிடமும் ஓயாமல்,
உன் சிரிப்பை கேட்டு
நான் தினமும் ஓடுவேனே…

நீ போகும் இடம் தெரியாது;
ஆனால்
நீ அருகில் இருக்கும் வரை
பாதை எதுவாக இருந்தாலும்
அது எனக்கு கவிதையே…</div>
